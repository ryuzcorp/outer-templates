// The Worker, declared for Void (https://void.cloud): bindings, assets and
// defaults in one typed file. `voidPlugin()` reads it (edits need a dev
// server restart) and the build emits `dist/ssr/wrangler.json`, from which
// `vite.config.ts` (`emitCelldConfig`) derives the deploy-root
// `dist/wrangler.json` that Outer deploys with celld.
import { defineConfig } from "void/config";

// The brand in one place: `brand.json` at the repo root names the app, and
// this head renders it into every page (title, meta, Open Graph, icons).
// Edit brand.json to rebrand — never the generated outputs.
import brand from "./brand.json";

export default defineConfig({
  // Document head for every page. Void's document shell adds none of these
  // itself: `charset` and `viewport` must stay first, or phones render the
  // page as a zoomed-out 980px desktop layout. The rest add the PWA manifest (generated by vite-plugin-pwa from `manifest` +
  // `pwaAssets` in vite.config.ts — the plugin owns its content and icons),
  // theme color, and link previews. Void renders this head on the server:
  // with no index.html the plugin cannot inject these links itself.
  head: {
    title: brand.name,
    titleTemplate: `%s | ${brand.name}`,
    htmlAttrs: { lang: "en" },
    meta: [
      { charset: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { name: "description", content: brand.description },
      { name: "theme-color", content: brand.accent },
      { name: "mobile-web-app-capable", content: "yes" },
      { name: "apple-mobile-web-app-capable", content: "yes" },
      { name: "apple-mobile-web-app-title", content: brand.shortName },
      { property: "og:title", content: brand.name },
      { property: "og:description", content: brand.description },
      { property: "og:type", content: "website" },
      { property: "og:site_name", content: brand.name },
    ],
    link: [
      { rel: "manifest", href: "/manifest.webmanifest" },
      { rel: "icon", href: "/favicon.svg", type: "image/svg+xml" },
      { rel: "apple-touch-icon", href: "/apple-touch-icon-180x180.png" },
    ],
  },
  cloudflare: {
    // The Worker name celld serves the app as.
    name: "outer-app",
    // The app's D1 database, provisioned by Outer on first deploy. Read it
    // in server modules with `env.DB` from `cloudflare:workers`.
    // `migrations_dir` is the repo folder `void db generate` writes and
    // `void db migrate` (and dev-server startup) applies locally; Outer
    // applies the committed files on deploy before the new code goes live.
    d1_databases: [{ binding: "DB", database_name: "app-db", migrations_dir: "db/migrations" }],
  },
  worker: {
    compatibility_date: "2026-09-01",
  },
});
